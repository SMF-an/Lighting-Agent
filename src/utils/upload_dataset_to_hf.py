import argparse
import os
from pathlib import Path

from dotenv import load_dotenv
from huggingface_hub import HfApi, ModelCard, create_repo, get_full_repo_name


load_dotenv()


def build_dataset_card(repo_id):
    return f"""---
language: en
license: mit
tags:
- lighting
- image-captioning
- dataset
- vision-language
---

# {repo_id}

This dataset contains lighting-effect images and paired English captions.

## Contents

- `images/`: lighting-effect PNG images
- `light_effect_captions.jsonl`: image-caption pairs generated by a vision-language model

## Usage
You can load this dataset using the Hugging Face Datasets library:

```python
from datasets import load_dataset
dataset = load_dataset("{repo_id}")
```
"""


def upload_dataset_folder(dataset_name, source_dir):
    token = os.getenv("HF_TOKEN")
    if not token:
        raise ValueError("Hugging Face token not found. Please set the HF_TOKEN environment variable.")
    
    api = HfApi(token=token)
    
    repo_id = get_full_repo_name(dataset_name)
    
    create_repo(
        repo_id=repo_id,
        repo_type="dataset",
        private=False,
        token=token,
        exist_ok=True,
    )

    api.upload_folder(
        folder_path=str(source_dir),
        path_in_repo="",
        repo_id=repo_id,
        repo_type="dataset",
        token=token,
    )
    
    card = ModelCard(content=build_dataset_card(repo_id))
    card.push_to_hub(repo_id)
    

def main() -> None:
    parser = argparse.ArgumentParser(description="Upload the lighting dataset to Hugging Face Datasets.")
    parser.add_argument(
        "--dataset-name",
        default="lighting-dataset",
        help="Name of the dataset repository to create on Hugging Face (e.g., 'my-username/my-lighting-dataset').",
    )
    parser.add_argument(
        "--source-dir",
        default="data/trial",
        help="Local dataset folder to upload (contains images/ and light_effect_captions.jsonl).",
    )
    args = parser.parse_args()
    
    source_dir = Path(args.source_dir)

    if not source_dir.exists():
        raise FileNotFoundError(f"Dataset folder not found: {source_dir}")

    upload_dataset_folder(
        dataset_name=args.dataset_name,
        source_dir=source_dir,
    )
    print(f"Uploaded {source_dir} to Hugging Face Datasets as '{args.dataset_name}'.")


if __name__ == "__main__":
    main()
